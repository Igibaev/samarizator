import Foundation
import SwiftUI

/// Все параметры "живости" персонажа: геометрия глаз, слежение за курсором,
/// моргание, саккады, дыхание.
///
/// Это главный файл Фазы 2 — автор будет вручную крутить числа здесь, глядя
/// на результат в debug-режиме (`FOCUS_DEBUG=1`), поэтому у каждой группы
/// есть комментарий с разумными пределами. Логика (ViewModel/View) не должна
/// меняться при подборе — только эти константы.
enum CharacterConfig {

    // MARK: - Геометрия глаз

    /// Персонаж сделан в минималистичной манере: тёмное тело (сама капсула)
    /// и два светлых глаза-щели поверх него. Никакой склеры с бегающим
    /// зрачком — выпуклые "мультяшные" глаза в вырезе экрана выглядят
    /// пугающе, а не дружелюбно.

    /// Ширина одной щели (её короткая ось).
    static let eyeWidth: CGFloat = 5

    /// Высота одной щели (её длинная ось). Отношение высоты к ширине задаёт
    /// характер: около 2.5-4 — спокойный внимательный взгляд, ближе к 1 —
    /// округлый удивлённый, меньше 1 — прищур.
    static let eyeHeight: CGFloat = 13

    /// Зазор между щелями.
    static let eyeSpacing: CGFloat = 7

    /// Наклон щелей в градусах. 0 — строго вертикально (текущий выбор
    /// автора). Ненулевой наклон уводит лицо от строгой симметрии и добавляет
    /// характера, но и читается как гримаса — включать осознанно.
    static let eyeTilt: Double = 0

    /// Насколько пара глаз смещается по телу при максимальном отклонении
    /// взгляда, в pt. Взгляд здесь передаётся не движением зрачка внутри
    /// глаза, а сдвигом самой пары по "лицу" — как у минималистичных
    /// персонажей без склеры.
    static let gazeMaxShift: CGFloat = 5

    static let eyeColor: Color = .white

    /// Сдвиг глаз вниз от центра капсулы, pt.
    ///
    /// 0 — по центру. Раньше здесь была поправка на то, что верх капсулы
    /// тонул в физическом вырезе; теперь капсула стоит СПРАВА от выреза и
    /// видна целиком, поэтому лицо центрируется естественно.
    static let eyesYOffset: CGFloat = 6

    // MARK: - Слежение за курсором

    /// Дистанция в pt от центра персонажа до курсора, на которой зрачок
    /// достигает максимального отклонения (нормированное смещение = 1).
    /// Меньше — глаза "дёргаются" уже при небольшом движении мыши рядом;
    /// больше — почти не двигаются, пока мышь не уедет далеко. Ориентир:
    /// треть-половина ширины типичного экрана.
    static let trackingRange: CGFloat = 700

    /// Радиус "мёртвой зоны" вокруг центра персонажа (в тех же pt, что
    /// `trackingRange`): пока курсор внутри неё, зрачки остаются по центру.
    /// Нужен, чтобы дрожание мыши на месте не заставляло зрачки постоянно
    /// микро-дёргаться.
    static let trackingDeadZoneRadius: CGFloat = 40

    /// Параметры пружины слежения (`SwiftUI.Animation.interactiveSpring`).
    /// `response` — время реакции пружины в секундах (меньше = резвее),
    /// `damping` — доля критического демпфирования (1 = без колебаний,
    /// меньше 1 = лёгкое перелётывание/пружинка на конце движения).
    static let trackingSpringResponse: Double = 0.35
    static let trackingSpringDamping: Double = 0.75

    // MARK: - Моргание

    /// Границы случайного интервала между морганиями, секунды.
    static let blinkMinInterval: Double = 3
    static let blinkMaxInterval: Double = 7

    /// Полная длительность одного моргания (закрытие + открытие), секунды.
    /// Должно быть быстрым — иначе персонаж выглядит сонным, а не бодрым.
    static let blinkDuration: Double = 0.12

    /// Вертикальный масштаб глаза в полностью закрытом состоянии.
    /// Не делаем строго 0 — иначе на полпути анимации может мелькнуть
    /// артефакт схлопывания в линию нулевой толщины.
    static let blinkClosedScaleY: CGFloat = 0.05

    /// Вероятность (0...1), что за одиночным морганием сразу последует
    /// второе — двойное моргание, характерное для живых существ, редкое,
    /// но не единичное.
    static let doubleBlinkProbability: Double = 0.15

    /// Пауза между первым и вторым морганием в двойном моргании, секунды.
    static let doubleBlinkPause: Double = 0.1

    // MARK: - Саккады

    /// Через сколько секунд полной неподвижности курсора включается
    /// саккада — самопроизвольный короткий взгляд в сторону и обратно,
    /// имитирующий то, как живой взгляд никогда не замирает насмерть.
    static let saccadeIdleThreshold: Double = 4

    /// Амплитуда саккады в тех же нормированных единицах, что и
    /// `pupilOffset` (0...1) — на сколько зрачок отклоняется от текущей
    /// точки покоя.
    static let saccadeAmplitude: CGFloat = 0.35

    /// Сколько секунд зрачок удерживается в отклонённой точке саккады,
    /// прежде чем начать возврат. Диапазон, а не константа: одинаковое
    /// удержание раз за разом считывается как ритм скрипта.
    static let saccadeMinHold: Double = 0.4
    static let saccadeMaxHold: Double = 1.2

    /// Пауза между саккадами, пока курсор продолжает стоять на месте.
    ///
    /// Без неё персонаж, оставленный в покое, дёргает глазами примерно раз в
    /// секунду без остановки — это читается как тревожность, а не как жизнь.
    /// Живой взгляд отвлекается редкими всплесками, а между ними спокоен.
    static let saccadeMinPause: Double = 2.5
    static let saccadeMaxPause: Double = 7

    /// Длительность самого рывка — должна быть очень короткой, почти
    /// мгновенной. Это ключевая деталь: если сделать рывок медленным,
    /// взгляд читается как "плавающий"/заторможенный, а не живой.
    static let saccadeJumpDuration: Double = 0.045

    /// Длительность возврата в точку покоя — заметно медленнее и мягче
    /// рывка (несимметрично специально).
    static let saccadeReturnDuration: Double = 0.25

    // MARK: - Дыхание

    /// Период полного цикла дыхания (вдох+выдох), секунды.
    static let breathPeriod: Double = 4

    /// Амплитуда масштаба от дыхания: пара глаз масштабируется между
    /// 1.0 и `1 + breathAmplitude`. Должна быть едва заметной — если
    /// дыхание бросается в глаза, амплитуда слишком велика (ориентир 2-3%).
    static let breathAmplitude: CGFloat = 0.025

    // MARK: - Состояния (Фаза 3)

    /// Длительность анимации перехода между `StateAppearance` двух состояний
    /// (форма/наклон глаз, цвет и интенсивность подсветки) в
    /// `CompanionStateMachine.setState`.
    static let stateTransitionDuration: Double = 0.4

    /// Размер и сила блюра мягкого свечения-подсветки позади глаз
    /// (`NotchRootView.highlightGlow`). Цвет и интенсивность задаёт
    /// `StateAppearance` конкретного состояния — эти два числа управляют
    /// только "пятном" как таковым, одинаковым для всех состояний.
    static let highlightGlowSize: CGFloat = 40
    static let highlightBlurRadius: CGFloat = 18

    /// Базовая амплитуда "подпрыгивания" в pt при
    /// `StateAppearance.bobAmplitudeMultiplier == 1`. Переиспользует уже
    /// идущий цикл дыхания в `EyesViewModel.startBreathing` — отдельного
    /// таймера под это нет (см. PHASE-3-PROMPT.md: "без второго набора
    /// таймеров").
    static let bobAmplitude: CGFloat = 4

    // MARK: - Debug-отображение

    /// Во сколько раз увеличивать персонажа в debug-режиме — иначе на
    /// реальном размере глаза (десятки pt) моргание и саккады трудно
    /// разглядеть в деталях.
    static let debugScale: CGFloat = 2

    /// На сколько pt сдвинуть персонажа вниз в debug-режиме, чтобы он не
    /// перекрывался краем физического выреза и был виден целиком (работает
    /// вместе с `AppearanceConfig.debugExtraHeight`, который вытягивает саму
    /// капсулу вниз).
    static let debugYOffset: CGFloat = 10
}
