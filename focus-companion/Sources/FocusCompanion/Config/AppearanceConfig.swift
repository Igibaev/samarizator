import Foundation
import SwiftUI

/// Единое место для всех "магических чисел" внешнего вида.
///
/// Идея: на Фазе 2-3 автор будет активно крутить визуал (радиусы, длительности
/// анимаций дыхания/моргания, цвета эмоций), и это не должно требовать правок
/// в логике окна или геометрии — только здесь.
enum AppearanceConfig {

    // MARK: - Геометрия капсулы

    /// Радиус скругления верхних углов капсулы (те, что "выгибаются наружу"
    /// и стыкуются с краем экрана вокруг выреза).
    static let topCornerRadius: CGFloat = 8

    /// Радиус скругления нижних углов капсулы (обычное скругление внутрь,
    /// продолжающее форму выреза вниз).
    static let bottomCornerRadius: CGFloat = 14

    /// Насколько тело свёрнутой капсулы продолжается ВПРАВО за правый край
    /// выреза.
    ///
    /// Само тело начинается от ЛЕВОГО края выреза и поглощает его целиком:
    /// иначе у правого края выреза видно скругление капсулы, то есть шов
    /// между вырезом и персонажем. Итоговая ширина тела =
    /// ширина выреза + это значение.
    static let collapsedExtensionRight: CGFloat = 62

    /// Насколько капсула свисает НИЖЕ физического выреза.
    ///
    /// 0 — капсула ровно по высоте выреза и целиком помещается в полосу
    /// меню-бара. `debugExtraHeight` прибавляется к этому значению отдельно.
    static let capsuleExtraDepth: CGFloat = 0

    /// Зазор между правым краем физического выреза и левым краем капсулы.
    /// 0 — капсула вплотную примыкает к вырезу и читается как его отросток.
    static let collapsedGapFromNotch: CGFloat = 0

    // MARK: - Раскрытая панель (Фаза 3)

    /// Радиусы скругления капсулы в РАСКРЫТОМ состоянии. Верхние — уже не
    /// обязаны точь-в-точь повторять кривизну выреза (раскрытая капсула
    /// заметно шире него), поэтому радиус крупнее и просто визуально мягче;
    /// нижние — тоже крупнее, пропорционально выросшей высоте. Оба
    /// анимируются между collapsed/expanded через `NotchShape.animatableData`.
    static let expandedTopCornerRadius: CGFloat = 22
    static let expandedBottomCornerRadius: CGFloat = 26

    /// Размер ОКНА панели — оно всегда в размере раскрытого состояния
    /// (решение автора №2 в PHASE-3-PROMPT.md: морфится только содержимое
    /// внутри, не сам `NSPanel.setFrame`, иначе два независимых механизма
    /// анимации дают рывки). Это же и размер капсулы в раскрытом состоянии —
    /// в раскрытом виде капсула занимает окно целиком, без отступов.
    ///
    /// Ориентир автора, не финальная подгонка — должен оставаться заметно
    /// больше `collapsedCapsuleFrame` (с учётом `debugExtraHeight`), иначе
    /// морф "раскрытия" будет визуально сжимать капсулу, а не расширять.
    static let expandedWidth: CGFloat = 320
    static let expandedHeight: CGFloat = 200

    // MARK: - Ховер (Фаза 3)

    /// Частота опроса `NSEvent.mouseLocation` для определения наведения —
    /// см. `HoverDetector`: опрос, а не `NSTrackingArea`/глобальный монитор,
    /// потому что должен одинаково работать и когда панель пропускает клики
    /// (свёрнуто), и когда перехватывает (раскрыто).
    static let hoverPollInterval: Double = 1.0 / 20.0

    /// Задержка перед раскрытием — гасит случайный пролёт курсора мимо
    /// капсулы. Обязательное требование ТЗ (PHASE-3-PROMPT.md).
    static let hoverExpandDelay: Double = 0.2

    /// Задержка перед сворачиванием — короче задержки раскрытия: гасит
    /// дрожание курсора у самой границы капсулы (иначе состояние мигает
    /// раскрылось-свернулось-раскрылось), но не должна ощущаться как
    /// залипание панели.
    static let hoverCollapseDelay: Double = 0.15

    /// Длительность самой морф-анимации (размер капсулы и радиусы углов).
    static let hoverMorphDuration: Double = 0.28

    // MARK: - Виртуальная капсула (для машин без выреза)

    /// Ширина виртуальной капсулы на экранах без физического выреза
    /// (MacBook без Face ID / внешний монитор). Ориентир из ТЗ — 200-300pt.
    static let virtualCapsuleWidth: CGFloat = 220

    // MARK: - Цвет

    /// Цвет капсулы: чёрный, под цвет корпуса и выреза.
    /// В debug-режиме — красный, иначе капсулу физически невозможно увидеть.
    static var capsuleColor: Color { isDebug ? .red : .black }

    // Матовое стекло (NSVisualEffectView, blendingMode .behindWindow) пробовали
    // и отказались: размытия не появлялось ни внутри SwiftUI, ни как contentView
    // панели с собственной maskImage. Основной неисключённый подозреваемый —
    // уровень окна .screenSaver (см. NotchPanel): на таких высоких уровнях
    // behind-window-размытие может не поддерживаться. Если захочется вернуться
    // к идее, начинать проверку оттуда.

    // MARK: - Отладка

    /// Включается переменной окружения FOCUS_DEBUG=1.
    ///
    /// Зачем нужен: в обычном режиме капсула чёрная и по размеру точно равна
    /// вырезу — то есть невидима by design, и отличить "работает идеально" от
    /// "не запустилось" глазами нельзя. Debug-режим красит её в красный и
    /// вытягивает вниз из-под выреза, чтобы геометрию можно было проверить.
    ///
    /// Переменная читается из окружения процесса, поэтому работает при запуске
    /// бинарника из терминала, но НЕ через `open` (тот не передаёт окружение).
    static let isDebug = ProcessInfo.processInfo.environment["FOCUS_DEBUG"] == "1"

    /// На сколько пунктов вытянуть капсулу ВНИЗ из-под выреза в debug-режиме.
    static var debugExtraHeight: CGFloat { isDebug ? 28 : 0 }
}
