import CoreGraphics

/// Даёт «давность» последнего пользовательского ввода (мышь, клавиатура,
/// трекпад) во всей системе — БЕЗ разрешений Accessibility.
///
/// Нужен ровно для одной вещи: понять, что человек отошёл или залип, и не
/// лезть с напоминанием, пока он активно печатает и кликает. Просить доступ
/// к клавиатуре ради напоминалки недопустимо, а `CGEventSource` (в отличие
/// от глобального монитора `.keyDown`) такого разрешения не требует: это тот
/// же системный источник, которым пользуются заставки и энергосбережение.
enum IdleTimeProvider {

    /// Конкретные типы ввода, по которым считается простой.
    ///
    /// Раньше здесь была одна константа `kCGAnyInputEventType` (0xFFFFFFFF),
    /// собранная вручную из заголовка `CGEventTypes.h`. Она НЕ КОМПИЛИРУЕТСЯ:
    /// `CGEventType` импортируется в Swift закрытым `enum`, а не non-frozen
    /// структурой с `RawRepresentable`, поэтому `init(rawValue:)` у него
    /// проваливающийся и возвращает `nil` для значения, которого нет в
    /// списке. Force-unwrap тут не решение, а отложенный краш на старте.
    ///
    /// Поэтому взят запасной вариант: минимум по нескольким конкретным типам.
    /// Он покрывает и мышь, и трекпад, и клавиатуру — этого достаточно, чтобы
    /// отличить «работает» от «отошёл».
    private static let inputEventTypes: [CGEventType] = [
        .mouseMoved,
        .leftMouseDown,
        .rightMouseDown,
        .leftMouseDragged,
        .rightMouseDragged,
        .keyDown,
        .flagsChanged,
        .scrollWheel,
    ]

    /// Секунд с последнего пользовательского ввода в системе — не только
    /// внутри этого приложения: `CGEventSource` видит весь сеанс.
    ///
    /// `.combinedSessionState` — источник с учётом объединённого состояния
    /// сеанса (в том числе удалённых событий вроде Screen Sharing), а не
    /// только локальных аппаратных.
    ///
    /// Минимум по типам, а не сумма и не среднее: «последний ввод» — это
    /// самое СВЕЖЕЕ событие любого из них.
    static func secondsSinceLastEvent() -> Double {
        inputEventTypes
            .map { CGEventSource.secondsSinceLastEventType(.combinedSessionState, eventType: $0) }
            .min() ?? .infinity
    }
}
